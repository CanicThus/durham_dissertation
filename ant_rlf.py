def test_class() -> None:
    agent = AntRLF(ants_per_iteration=10, max_iterations=20, random_seed=7)
    agent.load_graph(TEMPLATE_GRAPH_PATH)
    agent.solve(verbose=True)
    agent.print_result()


def main() -> None:
    test_class()


if __name__ == "__main__":
    main()
